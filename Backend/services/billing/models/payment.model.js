import mongoose from "mongoose";

const paymentSchema=new mongoose.Schema({
    userId:{
        type:String,
        required:true
    }, // userId is the id of the user who is making the payment and we will get userId from the request body when user is making the payment and then we will save it in our database
    orderId:{
        type:String,
        required:true
    },  // order is created in razorpay and we get orderId from razorpay when we create order in razorpay that means we have to create order in razorpay first and then we will get orderId from razorpay and then we will save it in our database
    paymentId:String, // on the other hand paymentId is generated by razorpay when the payment is successful and we will get paymentId from razorpay when the payment is successful and then we will save it in our database
    amount:Number, // amount is the total amount of the payment and we will get amount from the request body when user is making the payment and then we will save it in our database
    currency:{
        type:String,
        default:"INR"
    },
    credits:{
        type:Number
    }, // credits is the number of credits that user will get after successful payment and we will get credits from the request body when user is making the payment and then we will save it in our database
    plan:{
        type:String
    },
    status:{
        type:String,
        enum:["created","paid","failed"],
        default:"created"
    }
},{timestamps:true})

const Payment=mongoose.model("Payment",paymentSchema)
export default Payment