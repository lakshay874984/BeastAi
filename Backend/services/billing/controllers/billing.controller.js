export const createOrder = async (req, res) => {
    try {
        const { plan } = req.body // plan is the plan that user has selected and we will get plan from the request body when user is making the payment and then we will create order in razorpay and then we will get orderId from razorpay and then we will save it in our database
        const userId = req.headers["x-user-id"]
        const selectedPlan = PLANS[plan] // selectedPlan is the plan that user has selected and we will get selectedPlan from the PLANS object that we have defined in our config/Plans.js file and then we will create order in razorpay and then we will get orderId from razorpay and then we will save it in our database

        if (!selectedPlan) {
            return res.status(404).json({ message: "plan not found" })
        }

        const order = await razorpay.orders.create({
            amount: selectedPlan.amount * 100,
            currency: "INR",
            receipt: `receipt-${Date.now()}`
        }) // it creates the razorpay order and we will get orderId from razorpay when we create order in razorpay and then we will save it in our database and we are * 100 because razorpay accepts amount in paise and we are passing amount in rupees and we are using Date.now() to generate unique receipt id for each order  razopay return something like this { id: 'order_9A33XWu170gUtm', entity: 'order', amount: 50000, amount_paid: 0, amount_due: 50000, currency: 'INR', receipt: 'receipt-175...', status: 'created', attempts: 0, created_at: 1675292017 } and we will get orderId from razorpay when we create order in razorpay and then we will save it in our database

        await Payment.create({
            userId,
            orderId: order.id,
            amount: selectedPlan.amount,
            credits: selectedPlan.credits,
            plan: selectedPlan.id,
            currency: order.currency,
            status: order.status
        }) // it creates the payment in our database and we will save userId, orderId, amount, credits, plan, currency and status in our database and we will get userId from the request headers when user is making the payment and we will get orderId from razorpay when we create order in razorpay and we will get amount, credits and plan from the selectedPlan object that we have defined in our config/Plans.js file and we will get currency and status from the order object that we have created in razorpay
        // .creates autmatically saves in our database and on the other hand  that is new payemnt ({....}) syntax which doesnt autmtaically sotre in our databsase

        return res.status(200).json({ order, plan: selectedPlan })



    } catch (error) {
        return res.status(500).json({ message: `create order error ${error}` })
    }
}


