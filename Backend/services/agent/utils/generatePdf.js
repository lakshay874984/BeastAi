import PDFDocument from "pdfkit"
export const generatePdf=async (data)=>{ // we are using promise here because we want to know when our pdf is being fully genrated and when it is fully genrated we cant to just resolbe our promise
return new Promise((resolve,reject)=>{
    const doc=new PDFDocument({
        size:"A4",
        margin:50,
        info:{
            Author:"CortexAI",
            Title:data.title,
            Creator:"BeastAI"
        }
    })  /// so it just define the metadata of the pdf

const chunks=[]

doc.on("data",(chunk)=>chunks.push(chunk))  // is says that if any data is being goin inside the doc then just add its buffer to the chunks
doc.on("end",()=>resolve(Buffer.concat(chunks))) // when doc.end is beign called then the end eveent trigers and then all the buffer that is stored inside the chunks is beign concated and finally it is resolved by the promise and retuedn to the pdf agent 
doc.on("error",()=>reject) // trigeers if any erroir occurs

//title
doc
  .fontSize(28) 
  .text(data.title,{
    align:"center"
  })
  .fillColor("#111827") // sets the title

  if(data.subtitle){
    doc.moveDown(0.5)
  }

  //subtitle

  doc
  .fontSize(12)
  .text(data.subtitle,{
    align:"center"
  })
  .fillColor("#6B7280") // sets the subtitle
              

  doc.moveDown(2) // to leave spaces of 2 lines

  //sections

  data?.sections?.forEach(s => {  // loop on the section 

  doc
  .fontSize(18)
  .text(s.heading)
  .fillColor("#111827")

  doc.moveDown(0.5)

  s?.points?.forEach((p)=>{
     
  doc
  .fontSize(12)
  .text("• "+ p,{
    lineGap:5
  })
  .fillColor("#374151")
  })

  doc.moveDown()

  });


  //footer

doc.moveDown()

  doc
  .fontSize(10)
  .text("Generated By BeastAI",{
    align:"center"
  })
  .fillColor("#9CA3AF")

  doc.end()

})
}
